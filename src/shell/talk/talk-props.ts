export function talkPropSize(id: TalkPropId): TalkGridSize {
  const prop = talkProps[id];
  return talkGridSize(prop.grid, prop.palette);
}

// Paints a prop at (x, y), one canvas pixel per cell. Odd frames use the animated
// frame when the prop has one.
export function drawTalkProp(
  context: TalkArtContext,
  id: TalkPropId,
  x: number,
  y: number,
  frame = 0,
): void {
  const prop = talkProps[id];
  const grid =
    frame % 2 === 1 && prop.animated !== undefined ? prop.animated : prop.grid;
  drawTalkGrid(context, grid, prop.palette, x, y);
}
