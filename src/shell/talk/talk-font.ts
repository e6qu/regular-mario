export type TalkGlyph = readonly (readonly boolean[])[];

export class UnsupportedTalkCharacterError extends Error {
  constructor(readonly characters: readonly string[]) {
    super(
      `Talk font has no glyph for: ${characters.map((c) => JSON.stringify(c)).join(", ")}`,
    );
    this.name = "UnsupportedTalkCharacterError";
  }
}

function parseGlyph(character: string, rows: GlyphRows): TalkGlyph {
  if (rows.length !== talkGlyphRows - 1 && rows.length !== talkGlyphRows) {
    throw new Error(
      `Glyph ${JSON.stringify(character)} has ${rows.length} rows; expected 7 or 8.`,
    );
  }
  const padded = rows.length === talkGlyphRows ? rows : [...rows, blank];
  return padded.map((row) => {
    if (row.length !== talkGlyphColumns || !/^[.#]+$/.test(row)) {
      throw new Error(
        `Glyph ${JSON.stringify(character)} has a malformed row ${JSON.stringify(row)}.`,
      );
    }
    return [...row].map((cell) => cell === "#");
  });
}

const glyphs: ReadonlyMap<string, TalkGlyph> = new Map(
  Object.entries(glyphSource).map(([character, rows]) => [
    character,
    parseGlyph(character, rows),
  ]),
);

export function talkGlyph(character: string): TalkGlyph {
  const glyph = glyphs.get(character);
  if (glyph === undefined) {
    throw new UnsupportedTalkCharacterError([character]);
  }
  return glyph;
}

// Every character of `text` the font cannot draw, in order of first appearance.
export function unsupportedTalkCharacters(text: string): readonly string[] {
  return [...new Set([...text].filter((character) => !glyphs.has(character)))];
}
